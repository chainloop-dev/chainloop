// extractCmdLineFromCommand returns the full command hierarchy as a string from a cobra.Command
func extractCmdLineFromCommand(cmd *cobra.Command) string {
	var cmdHierarchy []string
	// Walk up to the root command, which is dropped from the hierarchy. The nil check is
	// what terminates the walk for a command that is not attached to the root: this runs on
	// the exit path of every command, including the ones that failed, and telemetry must
	// never be the reason the CLI panics.
	for currentCmd := cmd; currentCmd != nil && currentCmd.Use != appName; currentCmd = currentCmd.Parent() {
		cmdHierarchy = append([]string{currentCmd.Use}, cmdHierarchy...)
	}

	cmdLine := strings.Join(cmdHierarchy, " ")
	return cmdLine
}

// controlPlaneURL returns the control plane the CLI is configured to talk to.
func controlPlaneURL() string {
	return viper.GetString(confOptions.controlplaneAPI.viperKey)
}

// hashURL is the hash telemetry groups events by. It takes the URL rather than reading the
// configuration so that the telemetry child, which only receives the URL, computes the
// same value as the parent would.
func hashURL(url string) string {
	sum := sha256.Sum256([]byte(url))
	return hex.EncodeToString(sum[:])
}

func apiInsecure() bool {
	return viper.GetBool(confOptions.insecure.viperKey)
}

// apiMaxRecvMsgSize returns the configured gRPC max receive message size for
// the CLI's outbound connections, in bytes. 0 means "use grpcconn's default".
func apiMaxRecvMsgSize() int {
	return viper.GetInt(confOptions.maxRecvMsgSize.viperKey)
}

// setLocalOrganization updates the local organization configuration
func setLocalOrganization(orgName string) error {
	viper.Set(confOptions.organization.viperKey, orgName)
	return viper.WriteConfig()
}

func shouldAskForConfirmation(cmd *cobra.Command) bool {
	return isAPITokenPreferred(cmd) && cmd.Annotations[confirmWhenUserToken] == trueString
}

func isAPITokenPreferred(cmd *cobra.Command) bool {
	return cmd.Annotations[useAPIToken] == trueString
}

func cmdSupportsFederatedAuth(cmd *cobra.Command) bool {
	return cmd.Annotations[supportsFederatedAuthAnnotation] == trueString
}

func getConfigDir(appName string) string {
	return filepath.Join(xdg.ConfigHome, appName)
}

// processCAFlag reads CA file content and stores it as PEM if value is a file path
func processCAFlag(opt *confOpt) error {
	value := viper.GetString(opt.viperKey)
	if value == "" {
		return nil
	}

	// If it's a file path, read and store PEM content directly
	if _, err := os.Stat(value); err == nil {
		content, err := os.ReadFile(value)
		if err != nil {
			return fmt.Errorf("failed to read CA file %s: %w", value, err)
		}

		// Store PEM content directly
		viper.Set(opt.viperKey, string(content))
	}

	return nil
}
