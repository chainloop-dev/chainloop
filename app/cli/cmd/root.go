// Environment variable prefix for vipers
const envPrefix = "CHAINLOOP"

// pluginLessCommands are the commands that never make use of plugins, keyed by the first
// argument on the command line. Loading plugins starts a subprocess per installed plugin,
// so it is skipped for the commands that cannot benefit from it.
var pluginLessCommands = map[string]bool{
	"completion":    true,
	"help":          true,
	telemetryCmdUse: true,
}

// processStart is when this process began, as close to it as a package variable gets. The
// reported duration is measured from here rather than from the top of Execute because
// NewRootCmd runs first and loads plugins, which starts a subprocess and an RPC handshake
// per plugin. Timing from Execute would leave that out for exactly the users who have
// plugins installed, making their numbers incomparable with everyone else's.
var processStart = time.Now()

func Execute(rootCmd *cobra.Command) error {
	// The command outcome is reported from here, the only place that sees both ends of
	// every command, including the ones that fail and so skip cobra's post-run hooks.
	executed, err := rootCmd.ExecuteC()
	reportCommand(executed, time.Since(processStart), err)

	if err != nil {
		// The local file is pointing to the wrong organization, we remove it
		if v1.IsUserNotMemberOfOrgErrorNotInOrg(err) {
			if err := setLocalOrganization(""); err != nil {
				logger.Debug().Err(err).Msg("failed to remove organization from config")
			}
		}

		return err
	}

	return nil
}

func NewRootCmd(l zerolog.Logger) *cobra.Command {
	// Seed the root logger here and not only in PersistentPreRunE: cobra
	// rejects unknown subcommands and invalid flags before that hook runs, and
	// with SilenceErrors set main is the only place those errors get printed.
	// A zero-value zerolog.Logger has no writer and would drop them silently.
	logger = l

	rootCmd := &cobra.Command{
		Use:   appName,
		Short: "Chainloop Command Line Interface",
		// The generated reference for these commands is kept in this repository
		// rather than published to the documentation site, so the link points at
		// the file itself.
		Long: `Chainloop Command Line Interface

Command reference: ` + cliReferenceURL,
		SilenceErrors: true,
		SilenceUsage:  true,
		PersistentPreRunE: func(cmd *cobra.Command, _ []string) error {
			var err error
			logger, err = initLogger(l)
			if err != nil {
				return err
			}

			logger.Debug().Str("path", viper.ConfigFileUsed()).Msg("using config file")

			// Commands annotated with skipActionOptsInit don't need ActionOpts initialization
			// These are local-only commands that don't interact with the control plane
			if cmd.Annotations[skipActionOptsInit] == trueString {
				return nil
			}

			if apiInsecure() {
				logger.Debug().Msg("API contacted in insecure mode")
			}

			authToken, isUserToken, err := loadAuthToken(cmd)
			if err != nil {
				return err
			}
			authTokenIsUser = isUserToken

			// If the auth token is not set and the command supports federated auth, we try to discover the runner and use the federated token for the runner if available
			if authToken == "" && cmdSupportsFederatedAuth(cmd) {
				r := crafter.DiscoverRunner(authToken, logger)
				if r.IsAuthenticated() && r.FederatedToken() != "" {
					logger.Debug().Str("runner", r.ID().String()).Msg("using federated auth token")
					authToken = r.FederatedToken()
					// reset isUserToken to false because we are using a federated token and we don't want to ask for confirmation
					isUserToken = false
				}
			}

			var opts = []grpcconn.Option{
				grpcconn.WithInsecure(apiInsecure()),
				grpcconn.WithCLIVersion(fullVersion()),
			}

			if maxRecv := apiMaxRecvMsgSize(); maxRecv > 0 {
				opts = append(opts, grpcconn.WithMaxRecvMsgSize(maxRecv))
			}

			if caValue := viper.GetString(confOptions.controlplaneCA.viperKey); caValue != "" {
				// Check if the value is a file path, if it is we read the content and encode it to base64, if not we assume it's the content already
				if _, err := os.Stat(caValue); err == nil {
					opts = append(opts, grpcconn.WithCAFile(caValue))
				} else {
					opts = append(opts, grpcconn.WithCAContent(caValue))
				}
			}

			controlplaneURL := viper.GetString(confOptions.controlplaneAPI.viperKey)

			// If no organization is set in local configuration, we load it from server and save it
			orgName := viper.GetString(confOptions.organization.viperKey)
			if orgName == "" {
				conn, err := grpcconn.New(controlplaneURL, authToken, opts...)
				if err != nil {
					return err
				}

				currentContext, err := action.NewConfigCurrentContext(newActionOpts(logger, conn, authToken)).Run()
				if err == nil && currentContext.CurrentMembership != nil {
					if err := setLocalOrganization(currentContext.CurrentMembership.Org.Name); err != nil {
						return fmt.Errorf("writing config file: %w", err)
					}
				}
			}

			// reload the connection now that we have the org name
			orgName = viper.GetString(confOptions.organization.viperKey)
			if orgName != "" {
				opts = append(opts, grpcconn.WithOrgName(orgName))
			}

			// Warn users when the session is interactive, and the operation is supposed to use an API token instead
			if shouldAskForConfirmation(cmd) && authToken != "" && isUserToken && !flagYes {
				logger.Warn().Msg("User-attended mode detected. This is intended for local testing only. For CI/CD or automated workflows, please use an API token.")
				if !confirmationPrompt(fmt.Sprintf("This command will run against the organization %q", orgName)) {
					return errors.New("command canceled by user")
				}
			}

			conn, err := grpcconn.New(controlplaneURL, authToken, opts...)
			if err != nil {
				return err
			}

			ActionOpts = newActionOpts(logger, conn, authToken)

			// Add custom builtins to rego engine
			if err = builtins.RegisterDiscoverBuiltin(conn); err != nil {
				return fmt.Errorf("failed to register discover builtin: %w", err)
			}

			return nil
		},
		PersistentPostRunE: func(_ *cobra.Command, _ []string) error {
			if ActionOpts != nil {
				return cleanup(ActionOpts.CPConnection)
			}
			return nil
		},
	}

	rootCmd.SetHelpCommand(&cobra.Command{Hidden: true})

	rootCmd.PersistentFlags().StringVarP(&flagCfgFile, "config", "c", "", "Path to an existing config file (default is $HOME/.config/chainloop/config.toml)")

	rootCmd.PersistentFlags().String(confOptions.controlplaneAPI.flagName, defaultCPAPI, fmt.Sprintf("URL for the Control Plane API ($%s)", CalculateEnvVarName(confOptions.controlplaneAPI.viperKey)))
	cobra.CheckErr(viper.BindPFlag(confOptions.controlplaneAPI.viperKey, rootCmd.PersistentFlags().Lookup(confOptions.controlplaneAPI.flagName)))
	cobra.CheckErr(viper.BindEnv(confOptions.controlplaneAPI.viperKey, CalculateEnvVarName(confOptions.controlplaneAPI.viperKey)))

	// Custom CAs for the control plane
	rootCmd.PersistentFlags().String(confOptions.controlplaneCA.flagName, "", fmt.Sprintf("CUSTOM CA file for the Control Plane API (optional) ($%s)", CalculateEnvVarName(confOptions.controlplaneCA.viperKey)))
	cobra.CheckErr(viper.BindPFlag(confOptions.controlplaneCA.viperKey, rootCmd.PersistentFlags().Lookup(confOptions.controlplaneCA.flagName)))
	cobra.CheckErr(viper.BindEnv(confOptions.controlplaneCA.viperKey, CalculateEnvVarName(confOptions.controlplaneCA.viperKey)))

	rootCmd.PersistentFlags().String(confOptions.CASAPI.flagName, defaultCASAPI, fmt.Sprintf("URL for the Artifacts Content Addressable Storage API ($%s)", CalculateEnvVarName(confOptions.CASAPI.viperKey)))
	cobra.CheckErr(viper.BindPFlag(confOptions.CASAPI.viperKey, rootCmd.PersistentFlags().Lookup(confOptions.CASAPI.flagName)))
	cobra.CheckErr(viper.BindEnv(confOptions.CASAPI.viperKey, CalculateEnvVarName(confOptions.CASAPI.viperKey)))

	// Custom CAs for the CAS
	rootCmd.PersistentFlags().String(confOptions.CASCA.flagName, "", fmt.Sprintf("CUSTOM CA file for the Artifacts CAS API (optional) ($%s)", CalculateEnvVarName(confOptions.CASCA.viperKey)))
	cobra.CheckErr(viper.BindPFlag(confOptions.CASCA.viperKey, rootCmd.PersistentFlags().Lookup(confOptions.CASCA.flagName)))
	cobra.CheckErr(viper.BindEnv(confOptions.CASCA.viperKey, CalculateEnvVarName(confOptions.CASCA.viperKey)))

	rootCmd.PersistentFlags().BoolP("insecure", "i", false, fmt.Sprintf("Skip TLS transport during connection to the control plane ($%s)", CalculateEnvVarName(confOptions.insecure.viperKey)))
	cobra.CheckErr(viper.BindPFlag(confOptions.insecure.viperKey, rootCmd.PersistentFlags().Lookup("insecure")))
	cobra.CheckErr(viper.BindEnv(confOptions.insecure.viperKey, CalculateEnvVarName(confOptions.insecure.viperKey)))

	// Override the gRPC client-side max receive message size in bytes (0 = use default)
	rootCmd.PersistentFlags().Int(confOptions.maxRecvMsgSize.flagName, 0, fmt.Sprintf("Max size in bytes for incoming gRPC messages (0 = default %d) ($%s)", grpcconn.DefaultMaxRecvMsgSize, CalculateEnvVarName(confOptions.maxRecvMsgSize.viperKey)))
	cobra.CheckErr(viper.BindPFlag(confOptions.maxRecvMsgSize.viperKey, rootCmd.PersistentFlags().Lookup(confOptions.maxRecvMsgSize.flagName)))
	cobra.CheckErr(viper.BindEnv(confOptions.maxRecvMsgSize.viperKey, CalculateEnvVarName(confOptions.maxRecvMsgSize.viperKey)))

	rootCmd.PersistentFlags().BoolVar(&flagDebug, "debug", false, "Enable debug/verbose logging mode")
	rootCmd.PersistentFlags().StringVarP(&flagOutputFormat, "output", "o", "table", "Output format, valid options are json and table")

	// Override the oauth authentication requirement for the CLI by providing an API token
	rootCmd.PersistentFlags().StringVarP(&apiToken, "token", "t", "", fmt.Sprintf("API token. NOTE: Alternatively use the env variable %s", tokenEnvVarName))

	rootCmd.PersistentFlags().StringP(confOptions.organization.flagName, "n", "", "organization name")
	cobra.CheckErr(viper.BindPFlag(confOptions.organization.viperKey, rootCmd.PersistentFlags().Lookup(confOptions.organization.flagName)))

	// Do not ask for confirmation
	rootCmd.PersistentFlags().BoolVarP(&flagYes, "yes", "y", false, "Skip confirmation")

	rootCmd.AddCommand(newWorkflowCmd(), newAuthCmd(), NewVersionCmd(),
		newAttestationCmd(), newArtifactCmd(), newConfigCmd(),
		newIntegrationCmd(), newOrganizationCmd(), newCASBackendCmd(),
		newReferrerDiscoverCmd(), newPolicyCmd(), newApplyCmd(),
		newTraceCmd(), newTelemetryCmd(),
	)

	// Load plugins for root command and subcommands, except for the ones that cannot use
	// them. `telemetry` is in that list because it is the detached child that delivers an
	// analytics event: loading plugins there would spawn a subprocess and an RPC handshake
	// per installed plugin, for a process whose whole job is one HTTP request.
	if len(os.Args) == 1 || (len(os.Args) > 1 && !pluginLessCommands[os.Args[1]]) {
		pluginManager = plugins.NewManager(&logger)
		if err := loadAllPlugins(rootCmd); err != nil {
			logger.Error().Err(err).Msg("Failed to load plugins, continuing with built-in commands only")
		}
	}

	return rootCmd
}

// this could have been done using automatic + prefix but we want to have control and know the values
//
//	viper.AutomaticEnv()
//	viper.SetEnvPrefix(envPrefix)
//	viper.SetEnvKeyReplacer(strings.NewReplacer("-", "_", ".", "_"))
func CalculateEnvVarName(key string) string {
	// replace - with _ and . with _
	s := strings.ReplaceAll(key, "-", "_")
	s = strings.ReplaceAll(s, ".", "_")
	return fmt.Sprintf("%s_%s", envPrefix, strings.ToUpper(s))
}

func init() {
	cobra.OnInitialize(initConfigFile)
}

// isTelemetryDisabled checks if the telemetry is disabled by the user or if we are running a development version
func isTelemetryDisabled() bool {
	return os.Getenv(doNotTrackEnv) == "1" || os.Getenv(doNotTrackEnv) == trueString || Version == devVersion
}

// Logger returns the root logger. Hook commands swap it in place (see
// InitHookLogger), and main reads it for its final error line so that line
// shares the hook's colorless formatting during a git commit or push.
func Logger() zerolog.Logger {
	return logger
}

func initLogger(logger zerolog.Logger) (zerolog.Logger, error) {
	lvl := zerolog.InfoLevel
	if flagDebug {
		lvl = zerolog.DebugLevel
	}

	return logger.Level(lvl), nil
}

func initConfigFile() {
	// The telemetry child reads nothing from the config: everything it needs is either
	// compiled in or arrived in its payload. Skipping the setup keeps it from creating the
	// config directory and writing a default file, and from panicking below when that
	// directory cannot be created, in a process whose only job is one HTTP request.
	if isTelemetryFlushInvocation() {
		return
	}

	// An existing config file was passed as a flag and we use it as is
	if flagCfgFile != "" {
		viper.SetConfigFile(flagCfgFile)
		cobra.CheckErr(viper.ReadInConfig())
		return
	}

	// If no config file was passed as a flag we use the default one
	configPath := getConfigDir(appName)
	// Create the file if it does not exist
	if _, err := os.Stat(configPath); errors.Is(err, os.ErrNotExist) {
		err := os.MkdirAll(configPath, os.ModePerm)
		if err != nil {
			panic(fmt.Errorf("creating config file %s: %w", configPath, err))
		}
	}

	viper.AddConfigPath(configPath)
	viper.SetConfigType("toml")

	// Development uses a different version of the config file
	configName := "config"
	if Version == devVersion {
		configName = "config.devel"
	}

	viper.SetConfigName(configName)

	// Write the file only if it does not exist yet
	err := viper.SafeWriteConfig()

	// Capture the error if it's not that the file exists
	wantErr := viper.ConfigFileAlreadyExistsError("")
	if !errors.As(err, &wantErr) {
		cobra.CheckErr(err)
	}

	cobra.CheckErr(viper.ReadInConfig())
}

func newActionOpts(logger zerolog.Logger, conn *grpc.ClientConn, token string) *action.ActionsOpts {
	return &action.ActionsOpts{CPConnection: conn, Logger: logger, AuthTokenRaw: token, OutputFormat: flagOutputFormat, CLIVersion: fullVersion()}
}

func cleanup(conn *grpc.ClientConn) error {
	cleanupPlugins()
	if conn != nil {
		if err := conn.Close(); err != nil {
			return err
		}
	}
	return nil
}

// Load the controlplane based on the following order:
// 1. If the command requires an API token, we load it and fail otherwise
// 2. If the command does not require an API token, we
// 2.1 Return the token explicitly provided via the flag
// 2.2 Load the token from the environment variable and from the auth login config file
// 2.3 if they both exist, we default to the API token from the environment variable
// 2.4 otherwise to the one that's set
func loadAuthToken(cmd *cobra.Command) (string, bool, error) {
	// Load the APIToken from the env variable
	apiTokenFromVar := os.Getenv(tokenEnvVarName)

	// Load the user token from the config file
	userToken := viper.GetString(confOptions.authToken.viperKey)

	apiTokenFromFlagOrVar := apiToken
	if apiTokenFromFlagOrVar == "" {
		apiTokenFromFlagOrVar = apiTokenFromVar
	}

	// Prefer to use the API token if the command can use it, and it's provided (i.e. attestations)
	if isAPITokenPreferred(cmd) && apiTokenFromFlagOrVar != "" {
		return apiTokenFromFlagOrVar, false, nil
	}

	// Now we check explicitly provided API token via the flag
	if apiToken != "" {
		logger.Info().Msg("API token provided to the command line")
		return apiToken, false, nil
	}

	// If the API token env var is set we default to it. An explicitly exported $CHAINLOOP_TOKEN is a
	// stronger signal of intent than a (possibly stale) login session, and API tokens can now perform
	// the same operations as user credentials. We warn if user credentials are also present.
	if apiTokenFromVar != "" {
		if userToken != "" {
			logger.Warn().Msgf("Both user credentials and $%s set. Ignoring user credentials.", tokenEnvVarName)
		}
		return apiTokenFromVar, false, nil
	}

	return userToken, true, nil
}

